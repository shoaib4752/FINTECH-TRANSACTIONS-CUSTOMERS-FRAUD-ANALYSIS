SELECT * FROM CUSTOMERS
SELECT * FROM MERCHANTS
SELECT * FROM REFUNDS
SELECT * FROM RISK_FRAUD
SELECT * FROM TRANSACTIONS



-- Q 1 TOTAL TRANSACTIONS AND TRANSACTION VALUE

SELECT COUNT(DISTINCT TRANSACTION_ID) AS TOTAL_TRANSACTION,
SUM(TRANSACTION_AMOUNT) AS TOTAL_AMOUNT
FROM TRANSACTIONS

-- Q 2 AVERAGE TRANSACTION AMOUNT

SELECT AVG(TRANSACTION_AMOUNT) AS AVG_TRANSACTION_AMOUNT
FROM TRANSACTIONS

-- Q 3 YEAR WISE TRANSACTION AMOUNT AND TOTAL TRANSACTION

SELECT EXTRACT(YEAR FROM TRANSACTION_DATE) AS YEAR,
COUNT(DISTINCT TRANSACTION_ID) AS TOTAL_TRANSACTIONS,
SUM(TRANSACTION_AMOUNT) AS TOTAL_TRANSACTION_AMOUNT
FROM TRANSACTIONS
GROUP BY YEAR
ORDER BY YEAR

-- Q4 MONTH WISE TRANSACTIONS

SELECT EXTRACT(MONTH FROM TRANSACTION_DATE) AS MONTH,
COUNT(DISTINCT TRANSACTION_ID) AS TOTAL_TRANSACTIONS
FROM TRANSACTIONS
GROUP BY MONTH
ORDER BY MONTH

-- Q 5 HIGH VALUE TRANSACTIONS

SELECT TRANSACTION_ID, CUSTOMER_ID, TRANSACTION_AMOUNT
FROM TRANSACTIONS
ORDER BY TRANSACTION_AMOUNT DESC
LIMIT 10


-- Q 6 TRANSACTION STATUS BREAKDOWN

SELECT TRANSACTION_STATUS AS STATUS,
COUNT(DISTINCT TRANSACTION_ID) AS TOTAL_TRANSACTIONS
FROM TRANSACTIONS
GROUP BY STATUS
ORDER BY TOTAL_TRANSACTIONS DESC

-- Q 7 PAYMENT METHOD WISE TRANSACTIONS

SELECT PAYMENT_METHOD,
COUNT(DISTINCT TRANSACTION_ID) AS TOTAL_TRANSACTIONS
FROM TRANSACTIONS
GROUP BY PAYMENT_METHOD
ORDER BY TOTAL_TRANSACTIONS

-- Q 8 PAYMENT METHOD WISE TOTAL TRANSACTION AMOUNT

SELECT PAYMENT_METHOD,
SUM(TRANSACTION_AMOUNT) AS TOTAL_TRANSACTIONS_AMOUNT

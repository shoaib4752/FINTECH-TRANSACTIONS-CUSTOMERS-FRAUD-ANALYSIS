-- Q 28 (A) PAYMENT METHOD WISE REFUND

SELECT T.PAYMENT_METHOD, 
SUM(R.REFUND_AMOUNT) AS TOTAL_REFUND_AMOUNT
FROM REFUNDS R
JOIN TRANSACTIONS T
ON R.TRANSACTION_ID = T.TRANSACTION_ID
GROUP BY T.PAYMENT_METHOD
ORDER BY TOTAL_REFUND_AMOUNT DESC

-- (B) MERCHANT CATEGORY WISE REFUND

SELECT M.MERCHANT_CATEGORY, 
SUM(R.REFUND_AMOUNT) AS TOTAL_REFUND_AMOUNT
FROM REFUNDS R
JOIN TRANSACTIONS T
ON R.TRANSACTION_ID = T.TRANSACTION_ID
JOIN MERCHANTS M
ON T.MERCHANT_ID = M.MERCHANT_ID
GROUP BY M.MERCHANT_CATEGORY
ORDER BY TOTAL_REFUND_AMOUNT DESC


-- Q 29 TOTAL FRAUD

SELECT COUNT(Transaction_ID) AS TOTAL_FRAUD
FROM RISK_FRAUD
WHERE FRAUD_FLAG = 'Yes';


-- Q 30 Overall Fraud Pattern Analysis

SELECT T.PAYMENT_METHOD, T.CHANNEL, M.MERCHANT_CATEGORY, R.RISK_LEVEL,
COUNT(R.TRANSACTION_ID) AS TOTAL_FRAUD
FROM RISK_FRAUD R
JOIN TRANSACTIONS T
ON R.TRANSACTION_ID = T.TRANSACTION_ID
JOIN MERCHANTS M
ON T.MERCHANT_ID = M.MERCHANT_ID
WHERE R.FRAUD_FLAG = 'Yes'
GROUP BY T.PAYMENT_METHOD, T.CHANNEL, M.MERCHANT_CATEGORY, R.RISK_LEVEL
ORDER BY TOTAL_FRAUD DESC;
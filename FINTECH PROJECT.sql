ORDER BY TOTAL_TRANSACTIONS_AMOUNT

-- Q 9  PAYMENT METHOD WISE AVERAGE TRANSACTION AMOUNT

SELECT PAYMENT_METHOD,
AVG(TRANSACTION_AMOUNT) AS AVG_TRANSACTIONS_AMOUNT
FROM TRANSACTIONS
GROUP BY PAYMENT_METHOD
ORDER BY AVG_TRANSACTIONS_AMOUNT

-- Q 10 FAILURE AND DECLINED VALUES

SELECT PAYMENT_METHOD, TRANSACTION_STATUS,
COUNT(DISTINCT TRANSACTION_ID) AS TOTAL_TRANSACTIONS
FROM TRANSACTIONS
WHERE TRANSACTION_STATUS IN ('Failed', 'Declined')
GROUP BY PAYMENT_METHOD, TRANSACTION_STATUS
ORDER BY TOTAL_TRANSACTIONS DESC


